package br.com.weslleycampos.chat.feature.auth.signin

import android.content.Context
import androidx.compose.runtime.Composable
import androidx.compose.runtime.getValue
import androidx.compose.runtime.remember
import androidx.compose.runtime.rememberCoroutineScope
import androidx.compose.runtime.rememberUpdatedState
import androidx.compose.ui.platform.LocalContext
import androidx.credentials.CredentialManager
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.launch

@Composable
internal actual fun rememberGoogleSignInLauncher(
    onToken: (idToken: String, accessToken: String?) -> Unit,
    onError: (Throwable) -> Unit,
): () -> Unit {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    val currentOnToken by rememberUpdatedState(onToken)
    val currentOnError by rememberUpdatedState(onError)
    return remember(context, scope) {
        {
            scope.launch {
                try {
                    currentOnToken(requestGoogleIdToken(context), null)
                } catch (e: CancellationException) {
                    throw e
                } catch (ignoredUserDismissal: GetCredentialCancellationException) {
                } catch (e: Exception) {
                    currentOnError(e)
                }
            }
        }
    }
}

private suspend fun requestGoogleIdToken(context: Context): String {
    // Generated by the google-services plugin from google-services.json, so it has no R reference.
    val webClientId = context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
    check(webClientId != 0) {
        "default_web_client_id is missing: enable Google sign-in in Firebase and re-download google-services.json"
    }
    val request = GetCredentialRequest.Builder()
        .addCredentialOption(GetSignInWithGoogleOption.Builder(context.getString(webClientId)).build())
        .build()
    val credential = CredentialManager.create(context).getCredential(context, request).credential
    return GoogleIdTokenCredential.createFrom(credential.data).idToken
}
